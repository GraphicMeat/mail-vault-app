#!/usr/bin/env node
/**
 * Builds the full-text search index the docs and FAQ hub pages fetch.
 *
 * The site is static HTML with no build step for content, so the index is a
 * plain JSON file generated from the pages themselves: one entry per heading,
 * carrying the page title, the section heading, its anchor and its text. That
 * is what lets a search for `com.mailvault.app` land on the FAQ answer that
 * contains it. The hub pages used to filter their own link list, which only
 * ever saw question titles, so anything said in an answer was unfindable.
 *
 * One index per locale root (website/, website/de/, ...), written next to the
 * pages it describes, so a page fetches `<its own directory>/search-index.json`
 * and gets its own language. Locale pages are generated by i18n.mjs, so this
 * runs after `i18n.mjs build` — see .github/workflows/deploy-website.yml.
 *
 * Usage: node scripts/build-search-index.mjs [websiteDir]
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

const LOCALES = ['de', 'fr', 'es', 'it', 'pt-br', 'ja', 'ko', 'zh'];

// Directories that hold no reader-facing prose, and hub pages that are nothing
// but links to pages already indexed (they would return themselves for every
// query).
const SKIP_DIRS = new Set(['api', 'node_modules', 'src', 'i18n', 'assets', 'screenshots', 'oauth', ...LOCALES]);
const SKIP_FILES = new Set([
  'faq.html', 'docs.html', 'blog.html', 'index.html', 'mentioned-in.html',
  'billing-cancel.html', 'billing-success.html', 'download-stats.html', 'changelog.html',
]);

// Markers planted where the tags used to be, so one pass can strip the markup
// and still know where each heading started and what anchor encloses it.
const SEC = '\u0001';   // start of a section, followed by its anchor id
const HEAD = '\u0002';  // end of the anchor id, start of the heading text
const BODY = '\u0003';  // end of the heading text, start of the section body

const ENTITIES = {
  amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', copy: '©',
  mdash: '—', ndash: '–', rarr: '→', larr: '←',
  middot: '·', hellip: '…', times: '×', trade: '™',
  reg: '®', deg: '°', euro: '€', pound: '£',
};

const decode = s => s
  .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
  .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
  .replace(/&([a-z]+);/gi, (m, name) => ENTITIES[name.toLowerCase()] ?? m);

/** Sections of one page: [{ a: anchor, h: heading, x: text }]. */
export function sections(html) {
  const main = /<main\b[^>]*>([\s\S]*?)<\/main>/i.exec(html);
  if (!main) return [];
  const clean = main[1]
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<(script|style|svg|nav|figure|template)\b[\s\S]*?<\/\1>/gi, ' ');

  // Strip tags, planting a marker at every heading that carries the id
  // enclosing it — `<article id="x"><h2>` on the FAQ pages, `<h2 id="x">`
  // elsewhere, and nothing at all in the guides, which link to the page.
  let out = '';
  let lastId = '';
  let pos = 0;
  const tag = /<(\/?)([a-zA-Z][a-zA-Z0-9]*)\b([^>]*)>/g;
  let m;
  while ((m = tag.exec(clean))) {
    out += clean.slice(pos, m.index) + ' ';
    pos = tag.lastIndex;
    const [, closing, name, attrs] = m;
    const heading = /^h[1-4]$/i.test(name);
    if (closing) {
      if (heading) out += BODY;
      continue;
    }
    const id = /\bid="([^"]+)"/.exec(attrs);
    if (id) lastId = id[1];
    if (heading) {
      out += SEC + lastId + HEAD;
      lastId = '';
    }
  }
  out += clean.slice(pos);

  const norm = s => decode(s).replace(/\s+/g, ' ').trim();
  return out.split(SEC).slice(1).map(chunk => {
    const [anchor, rest = ''] = splitOnce(chunk, HEAD);
    const [heading, body = ''] = splitOnce(rest, BODY);
    return { a: anchor.trim(), h: norm(heading), x: norm(body) };
  }).filter(s => s.h || s.x);
}

const splitOnce = (s, sepChar) => {
  const i = s.indexOf(sepChar);
  return i === -1 ? [s] : [s.slice(0, i), s.slice(i + 1)];
};

function pages(root, dir = root, found = []) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (dir === root && SKIP_DIRS.has(name)) continue;
      pages(root, full, found);
    } else if (name.endsWith('.html') && !(dir === root && SKIP_FILES.has(name))) {
      found.push(full);
    }
  }
  return found;
}

export function buildIndex(root) {
  const entries = [];
  for (const file of pages(root).sort()) {
    const html = readFileSync(file, 'utf8');
    const rawTitle = /<title>([\s\S]*?)<\/title>/i.exec(html)?.[1] ?? '';
    const title = decode(rawTitle.replace(/\s*[|—-]\s*MailVault.*$/i, '').replace(/\s+/g, ' ').trim());
    const url = relative(root, file).split(sep).join('/');
    for (const s of sections(html)) {
      entries.push({ u: s.a ? `${url}#${s.a}` : url, t: title, h: s.h, x: s.x });
    }
  }
  return entries;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const websiteDir = process.argv[2] ?? join(process.cwd(), 'website');
  let total = 0;
  for (const root of [websiteDir, ...LOCALES.map(l => join(websiteDir, l))]) {
    if (!existsSync(root)) continue;
    const index = buildIndex(root);
    const out = join(root, 'search-index.json');
    writeFileSync(out, JSON.stringify(index));
    total += index.length;
    console.log(`${relative(websiteDir, out)}: ${index.length} sections, ${(statSync(out).size / 1024).toFixed(0)} KB`);
  }
  console.log(`${total} sections indexed`);
}
