//! The Insights aggregation: sender, day and timeline counts over the header
//! copies an Insights snapshot pages out (`insights_begin_snapshot` /
//! `insights_read_page` in the daemon). Ported from the app's
//! `src/utils/insights/model.js` and `calendar.js`, which ran in a web
//! worker; the daemon builds one [`Model`] per Insights visit
//! (`insights.build`) and answers `insights.aggregate` and
//! `insights.messages` from it, so the app only renders.
//!
//! Parity: `tests/fixtures/insights-model-cases.json` holds what the JS
//! answered for every fixture its unit suite used (generated by
//! `scripts/insights-model-golden.test.mjs`, deleted with the JS; see the
//! commit that added the fixture), and the
//! tests below require the same answers. Keys (`message:[...]`,
//! `physical:[...]`, `:copy-N`), ISO instants (`.sssZ`) and the JS string
//! order (UTF-16 code units) are kept exactly, because the app uses them as
//! identifiers and compares them as strings.

