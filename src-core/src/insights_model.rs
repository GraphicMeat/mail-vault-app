        assert_eq!(key("2026-09-08T21:30:00Z", "Europe/Vilnius").as_deref(), Some("2026-09-09"));
        assert_eq!(key("2026-09-09T00:30:00+03:00", "Europe/Vilnius").as_deref(), Some("2026-09-09"));
        assert_eq!(key("2026-09-08T21:30:00Z", "America/New_York").as_deref(), Some("2026-09-08"));
        assert_eq!(key("2026-03-29T00:59:00Z", "Europe/Vilnius").as_deref(), Some("2026-03-29"));
        assert_eq!(key("2026-10-25T01:30:00Z", "Europe/Vilnius").as_deref(), Some("2026-10-25"));
