    #[test]
    fn instants_normalize_like_to_iso_string_and_reject_impossible_times() {
        let norm = |raw: &str| parse_instant(raw).map(iso);
        assert_eq!(norm("2026-09-08T21:30:00Z").as_deref(), Some("2026-09-08T21:30:00.000Z"));
        assert_eq!(norm("2026-09-09T00:30:00+03:00").as_deref(), Some("2026-09-08T21:30:00.000Z"));
        assert_eq!(norm("2026-09-05T23:30:00-04:00").as_deref(), Some("2026-09-06T03:30:00.000Z"));
        assert_eq!(norm("2026-09-07T10:00:00.1Z").as_deref(), Some("2026-09-07T10:00:00.100Z"));
        for bad in ["nonsense", "2026-02-30T10:00:00Z", "2026-09-05T24:00:00Z", "2026-09-05T10:00:00+24:00", "2026-09-05T10:00:00"] {
            assert_eq!(norm(bad), None, "{bad}");
        }
    }

    /// A 50k-copy mailbox (the size that stresses search) builds and
    /// answers a year query well inside a click, and says how big the reply
    /// the app parses is.
    #[test]
    fn a_fifty_thousand_copy_model_answers_a_year_query() {
        let options = json!({"accounts": [{"id": "a", "email": "me@example.test"}], "ownAddressesByAccount": {}});
        let copies: Vec<Value> = (0..50_000u32)
            .map(|i| {
                let day = 1 + i % 28;
                let month = 1 + (i / 28) % 12;
                json!({"accountId": "a", "mailbox": "INBOX", "uid": i + 1, "uidValidity": 1, "source": "server-cache",
                    "origin": null, "messageId": format!("<m{i}@test>"),
                    "from": {"address": format!("person{}@example.test", i % 40), "name": format!("Person {}", i % 40)},
                    "to": [{"address": "me@example.test"}], "cc": [], "bcc": [], "subject": format!("Message {i}"),
                    "messageDate": format!("2026-{month:02}-{day:02}T10:00:00Z"),
                    "receivedAt": format!("2026-{month:02}-{day:02}T10:00:05Z"), "sentAt": null,
                    "dateEvidence": {"received": "imap-internaldate", "sent": "unknown"}, "flags": [],
                    "specialUse": "\\Inbox", "listId": null, "listUnsubscribe": null, "precedence": null})
            })
            .collect();
        let started = std::time::Instant::now();
        let model = build(&copies, &options);
        let built = started.elapsed();
        let query = json!({"accountIds": ["a"], "startDate": "2026-01-01", "endDate": "2026-12-31",
            "timeZone": "Europe/Vilnius", "direction": "received", "senderAddress": null, "hideAutomated": false,
            "timelineBucket": "week", "senderSort": "recent"});
        let started = std::time::Instant::now();
        let result = model.query(&query).unwrap();
        let queried = started.elapsed();
        assert_eq!(result["totals"]["received"], 50_000);
        assert_eq!(result["senders"].as_array().unwrap().len(), 40);
        let bytes = result.to_string().len();
        eprintln!("insights 50k: build {built:?}, week query {queried:?}, reply {bytes} bytes");
    }
